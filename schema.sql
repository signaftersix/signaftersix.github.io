-- Lock reviewed files when the request advances beyond pending review, and
-- start the 7-day deletion clock when an appointment is completed.
create or replace function public.request_status_side_effects()
returns trigger language plpgsql security definer set search_path=public as $$
begin
  if new.status in ('approved','awaiting_payment','confirmed','completed') and old.status is distinct from new.status then
    update public.request_documents set locked=true where request_id=new.id;
  end if;
  if new.status='completed' and old.status is distinct from 'completed' then
    new.completed_at=coalesce(new.completed_at,now());
    update public.request_documents set delete_after=coalesce(delete_after,now()+interval '7 days') where request_id=new.id;
  end if;
  return new;
end $$;
drop trigger if exists trg_request_status_side_effects on public.appointment_requests;
create trigger trg_request_status_side_effects before update on public.appointment_requests for each row execute function public.request_status_side_effects();
