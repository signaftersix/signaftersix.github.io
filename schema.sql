create table if not exists public.request_documents (
  id uuid primary key default gen_random_uuid(),
  request_id uuid not null references public.appointment_requests(id) on delete cascade,
  storage_path text not null unique,
  original_name text not null,
  mime_type text not null,
  byte_size bigint not null,
  locked boolean not null default false,
  delete_after timestamptz,
  created_at timestamptz not null default now()
);

create table if not exists public.request_management_links (
  request_id uuid primary key references public.appointment_requests(id) on delete cascade,
  management_token text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.quote_revisions (
  id uuid primary key default gen_random_uuid(),
  request_id uuid not null references public.appointment_requests(id) on delete cascade,
  version integer not null,
  previous_total numeric(10,2) not null,
  revised_total numeric(10,2) not null,
  breakdown jsonb not null,
  customer_acceptance_required boolean not null,
  accepted_at timestamptz,
  expires_at timestamptz,
  created_at timestamptz not null default now()
);

create table if not exists public.availability_blocks (
  id uuid primary key default gen_random_uuid(),
  starts_at timestamptz not null,
  ends_at timestamptz not null,
  reason text,
  source text not null default 'manual',
  external_event_id text,
  created_at timestamptz not null default now()
);

create table if not exists public.audit_log (
  id bigint generated by default as identity primary key,
  actor_user_id uuid references auth.users(id) on delete set null,
  request_id uuid references public.appointment_requests(id) on delete set null,
  action text not null,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create or replace function public.touch_updated_at()
returns trigger language plpgsql as $$ begin new.updated_at=now(); return new; end $$;
drop trigger if exists trg_touch_request on public.appointment_requests;
create trigger trg_touch_request before update on public.appointment_requests for each row execute function public.touch_updated_at();

