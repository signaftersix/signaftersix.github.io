  service_unit text,
  service_zip text,
  location_notes text,
  emergency_opening boolean not null default false,
  one_way_miles numeric(7,2),
  one_way_travel_seconds integer,
  duration_minutes integer not null default 30,
  document_type text not null,
  notarial_act text not null,
  signer_count integer,
  act_count integer,
  acts_unknown boolean not null default false,
  needs_witnesses boolean not null default false,
  document_notes text,
  customer_comments text,
  accommodations jsonb not null default '[]'::jsonb,
